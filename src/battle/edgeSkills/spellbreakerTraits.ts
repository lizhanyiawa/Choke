export function spellbreakerTraitArt(id?: string): Trait | undefined {
  if (!id?.startsWith("spellbreaker/")) return undefined
  const [, rarity, slot = ""] = id.split("/")
  const rows = slot.startsWith("P") ? passives : slot.startsWith("G") ? golds : undefined
  return rows?.[rarity as Rarity]?.[Number(slot.slice(1)) - 1]
}
