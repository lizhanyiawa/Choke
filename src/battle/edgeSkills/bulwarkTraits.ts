const traits = new Map<string, ArmorTrait>()
for (const [prefix, ranks] of [["P", passives], ["G", golden]] as const) {
  for (const [rarity, entries] of Object.entries(ranks))
    entries.forEach((entry, i) => traits.set("bulwark/" + rarity + "/" + prefix + (i + 1), entry))
}

export const bulwarkTraitArt = (id?: string) => id ? traits.get(id) : undefined
