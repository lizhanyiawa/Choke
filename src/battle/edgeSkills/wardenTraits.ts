export function wardenTraitArt(id?: string) {
  if (!id?.startsWith("warden/")) return
  const [, rarity, slot] = id.split("/")
  const byRank = slot?.startsWith("P") ? passives : slot?.startsWith("G") ? golden : undefined
  return byRank?.[rarity as Rarity]?.[Number(slot.slice(1)) - 1]
}
