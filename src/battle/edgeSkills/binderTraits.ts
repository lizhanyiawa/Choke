export function binderTraitArt(id?: string) {
  if (!id?.startsWith("binder/")) return
  const [, rarity, slot = ""] = id.split("/")
  const number = Number(slot.slice(1))
  const index = slot.startsWith("P") && number >= 1 && number <= 8 ? number - 1
    : slot.startsWith("G") && number >= 1 && number <= 2 ? number + 7 : -1
  return repertoire[rarity as Rarity]?.[index]
}
