export function berserkerTraitArt(id?: string) {
  if (!id?.startsWith("berserker/")) return
  const [, rarity, slot] = id.split("/")
  const table = slot?.startsWith("P") ? passives : slot?.startsWith("G") ? golds : undefined
  return table?.[rarity as Rarity]?.[Number(slot.slice(1)) - 1]
}
