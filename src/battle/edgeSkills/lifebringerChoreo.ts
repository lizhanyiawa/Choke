export type LifebringerMotif = (typeof repertoire)[keyof typeof repertoire][number]["motif"]
export function lifebringerChoreography(id?: string) {
  if (!id?.startsWith("lifebringer/")) return
  const [, rarity, slot = ""] = id.split("/")
  return slot.startsWith("A") ? repertoire[rarity as Rarity]?.[Number(slot.slice(1)) - 1] : undefined
}

