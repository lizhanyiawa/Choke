const perRecipient = new Set(["R/P4", "E/P1", "E/P4", "L/P2", "Prismatic/P1", "Prismatic/P2", "Prismatic/P4", "Prismatic/P7"])
for (const id of perRecipient) {
  const [rank, slot] = id.split("/")
  repertoire[rank as Rarity][Number(slot.slice(1)) - 1].cooldown = 0
}

export function dancerTraitArt(id?: string) {
  if (!id?.startsWith("dancer/")) return
  const [, rank, slot = ""] = id.split("/")
  const value = Number(slot.slice(1))
  const index = slot.startsWith("P") && value >= 1 && value <= 8 ? value - 1
    : slot.startsWith("G") && value >= 1 && value <= 2 ? value + 7 : -1
  return repertoire[rank as Rarity]?.[index]
}
