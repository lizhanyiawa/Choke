export function bardTraitArt(id?: string) {
  if (!id?.startsWith("bard/")) return
  const [, rarity, slot] = id.split("/")
  if (!slot || !/^(P[1-8]|G[12])$/.test(slot)) return
  return score[rarity as Rarity]?.[Number(slot[1]) - 1 + (slot[0] === "G" ? 8 : 0)]
}
